function normalizeLookupText(text: string) {
  return text.replace(/\s+/g, ' ').trim();
}

export function getCanonicalInlineText(text: string) {
  const normalizedText = normalizeLookupText(text);
  if (!normalizedText) return text;

  const dictionaries: Array<Record<string, string>> = [
    ...Object.values(inlineText),
    ...Object.values(projectText),
    ...Object.values(saasText),
  ];

  for (const dictionary of dictionaries) {
    for (const [source, translated] of Object.entries(dictionary)) {
      if (
        normalizeLookupText(source) === normalizedText ||
        normalizeLookupText(translated) === normalizedText
      ) {
        return source;
      }
    }
  }

  return text;
}

export function translateInlineText(language: string, text: string) {
  const shortLanguage = language.split('-')[0] as InlineLanguage;
  const canonicalText = getCanonicalInlineText(text);
  const translatedText = inlineText[shortLanguage]?.[canonicalText];
  if (shortLanguage === 'en') return translatedText ?? canonicalText;
  return translatedText ?? projectText[shortLanguage]?.[canonicalText] ?? saasText[shortLanguage]?.[canonicalText] ?? canonicalText;
}

export function useInlineText() {
  const { i18n } = useTranslation();

  return useCallback(
    (text: string) => translateInlineText(i18n.language, text),
    [i18n.language],
  );
}
